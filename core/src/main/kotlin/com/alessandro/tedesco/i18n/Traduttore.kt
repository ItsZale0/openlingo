    /** Translates [testo] to English when the interface language is English. */
    fun traduci(testo: String): String {
        if (lingua != "en") return testo
        esatto[testo]?.let { return it }
        esatto[testo.trim()]?.let { return it }
        for ((schema, sostituzione) in schemi) {
            if (schema.matches(testo)) {
                return schema.replace(testo, sostituzione)
            }
        }
        return testo
    }
}

/** Short alias used at the call sites. */
fun t(testo: String): String = Traduttore.traduci(testo)